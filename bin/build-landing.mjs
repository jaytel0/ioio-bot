import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
const license = await readFile('web/vendor/bloub/LICENSE', 'utf8');
const result = await build({banner:{js:'/* Vendored bloub engine\n'+license+'*/'},entryPoints:['web/landing.ts'],bundle:true,write:false,minify:true,format:'iife',target:['safari16','chrome110'],legalComments:'inline'});
const source = '// Generated by npm run build:landing; edit web/ instead.\nexport const landingScript = '+JSON.stringify(result.outputFiles[0].text)+';\n';
await writeFile('src/generated/landing-script.ts', source);
